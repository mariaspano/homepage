#!/usr/bin/env python3
"""Generate website fragments from data/*.yml.

Runs automatically before every `quarto render` (pre-render in _quarto.yml).
Writes:
  _publications.md  -> included by publications.qmd
  _home-stats.md    -> included by index.qmd
"""
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SECTIONS = [
    ("working", "Working Papers"),
    ("article", "Journal Articles"),
    ("book", "Books & Edited Volumes"),
    ("chapter", "Book Chapters"),
    ("proceedings", "Conference Proceedings"),
    ("other", "Technical Reports & Software"),
]
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()


def load(name):
    with open(ROOT / "data" / name, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def build_publications(pubs):
    out = ["<!-- generated by scripts/build_publications.py from data/publications.yml: do not edit -->", ""]
    for key, title in SECTIONS:
        items = [p for p in pubs if p["type"] == key]
        if not items:
            continue
        # newest first; stable for equal years (keeps hand-curated order)
        items.sort(key=lambda p: -(p.get("year") or 0))
        out += [f"## {title}", ""]
        for p in items:
            cit = " ".join(str(p["citation"]).split())
            if p.get("review"):
                cit += " [new]{.ms-badge-new}"
            out += [f"- {cit}", ""]
    return "\n".join(out)


def fmt_int(n):
    return f"{n:,}"


def build_stats(pubs, m):
    total = len(pubs)
    journals = sum(p["type"] == "article" for p in pubs)
    d = m["updated"] if isinstance(m["updated"], date) else date.fromisoformat(str(m["updated"]))
    when = f'{m.get("source", "Google Scholar")}, {MONTHS[d.month - 1]} {d.year}'
    cit = m["citations"]
    cit_label = f"{fmt_int(cit // 10 * 10)}+" if cit >= 100 else str(cit)
    tiles = [
        ("var(--coral)", f"{total}", "Scientific publications", f"{journals} journal articles"),
        ("var(--teal)", cit_label, "Citations", when),
        ("var(--violet)", "3", "Open-source R packages<br>(bibliometrix · TALL · themescopeR)", None),
        ("#E89A00", str(m["h_index"]), "h-index", when),
    ]
    html = ['<!-- generated by scripts/build_publications.py: do not edit -->',
            '<div class="ms-wrap">', '<div class="ms-stats">']
    for color, n, label, small in tiles:
        sm = f"<br><small>{small}</small>" if small else ""
        html.append(f'<div class="ms-stat" style="--accent: {color}"><span class="ms-stat-n">{n}</span>'
                    f'<span class="ms-stat-l">{label}{sm}</span></div>')
    html += ["</div>", "</div>", ""]
    return "\n".join(html)


def main():
    pubs = load("publications.yml")["publications"]
    metrics = load("metrics.yml")
    (ROOT / "_publications.md").write_text(build_publications(pubs), encoding="utf-8")
    (ROOT / "_home-stats.md").write_text(build_stats(pubs, metrics), encoding="utf-8")
    print(f"build_publications: {len(pubs)} publications")


if __name__ == "__main__":
    main()
